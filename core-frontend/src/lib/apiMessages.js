export function translateApiMessage(message) {
  if (typeof message !== 'string') return message;
  const trimmed = message.trim();
  if (API_MESSAGES_VI[trimmed]) return API_MESSAGES_VI[trimmed];
  if (/^Please provide a valid name, email, and password/.test(trimmed)) {
    return 'Vui lòng nhập họ tên, email hợp lệ và mật khẩu từ 8 ký tự.';
  }
  if (/^Rating must be 1/.test(trimmed)) return 'Đánh giá phải từ 1 đến 5 sao; nội dung tối đa 2000 ký tự.';
  if (/^Provide a valid non-zero stock adjustment/.test(trimmed)) return 'Hãy nhập số lượng điều chỉnh khác 0 và lý do (3–300 ký tự).';
  return message;
}
