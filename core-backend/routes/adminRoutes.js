const express=require('express');
const admin=require('../controllers/adminController');
const {requireAuth,requireRole}=require('../middleware/authMiddleware');
const router=express.Router();
router.use(requireAuth,requireRole('ADMIN'));
router.get('/dashboard',admin.dashboard);
router.get('/products',admin.listProducts);
router.post('/products',admin.createProduct);
router.put('/products/:id',admin.updateProduct);
router.post('/products/:id/inventory',admin.adjustInventory);
router.delete('/products/:id',admin.archiveProduct);
router.get('/inventory',admin.listInventory);
router.get('/categories',admin.listCategories);
router.post('/categories',admin.saveCategory);
router.put('/categories/:id',admin.saveCategory);
router.delete('/categories/:id',admin.archiveCategory);
router.get('/banners',admin.listBanners);
router.post('/banners',admin.createBanner);
router.put('/banners/:id',admin.updateBanner);
router.delete('/banners/:id',admin.archiveBanner);
router.get('/orders',admin.listOrders);
router.get('/orders/:id',admin.adminOrderDetail);
router.patch('/orders/:id/status',admin.updateOrderStatus);
router.patch('/orders/:id/shipping',admin.updateShipping);
router.get('/customers',admin.listCustomers);
router.patch('/customers/:id/status',admin.setCustomerStatus);
router.patch('/customers/:id/role',admin.setUserRole);
router.get('/deletion-requests',admin.listDeletionRequests);
router.patch('/deletion-requests/:id',admin.reviewDeletionRequest);
router.get('/coupons',admin.listCoupons);
router.post('/coupons',admin.saveCoupon);
router.put('/coupons/:id',admin.saveCoupon);
router.delete('/coupons/:id',admin.archiveCoupon);
router.get('/returns',admin.listReturns);
router.patch('/returns/:id',admin.updateReturn);
router.get('/reviews',admin.listReviews);
router.patch('/reviews/:id',admin.moderateReview);
module.exports=router;
